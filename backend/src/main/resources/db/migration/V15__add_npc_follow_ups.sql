create table npc_follow_ups (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone default now() not null,
    updated_at timestamp(6) with time zone default now() not null,
    conversation_id bigint not null,
    delivered_at timestamp(6) with time zone,
    delivered_conversation_id bigint,
    item varchar(40) not null,
    item_ko varchar(20) not null,
    npc_id bigint not null,
    ready_at timestamp(6) with time zone not null,
    user_id bigint not null,
    primary key (id),
    constraint uk_npc_follow_ups_conversation unique (conversation_id)
);

create index idx_npc_follow_ups_user_npc
    on npc_follow_ups (user_id, npc_id);
