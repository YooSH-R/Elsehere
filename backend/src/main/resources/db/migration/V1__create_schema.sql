-- Flyway 도입 전까지 엔티티 매핑(ddl-auto)이 만들던 스키마를 그대로 옮긴 첫 마이그레이션이다.
-- 유니크 제약 이름은 ddl-auto=update로 만든 기존 DB(dev, 팀원 로컬)와 같도록 Hibernate가 붙이던 이름(uk...)을 쓴다.
-- 기존 DB는 이 파일을 실행하지 않고 V1로 인정(baseline)한다. 차이는 V2에서 맞춘다.

create table ai_requests (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone default now() not null,
    updated_at timestamp(6) with time zone default now() not null,
    audio_ms integer,
    charged_tokens integer default 0 not null,
    conversation_id bigint,
    input_tokens integer default 0 not null,
    kind varchar(20) not null check ((kind in ('STT','GUARD','JUDGE','NPC','TTS','HINT','MEANING','FEEDBACK','MEMORY'))),
    model varchar(50),
    output_tokens integer default 0 not null,
    request_id uuid not null,
    reserved_tokens integer default 0 not null,
    settled_at timestamp(6) with time zone,
    status varchar(20) not null check ((status in ('RESERVED','OK','FAILED','BLOCKED'))),
    user_id bigint not null,
    primary key (id),
    constraint ukhjwodionsyjdqjr1w8lbxkfv0 unique (request_id, kind)
);

create table conversation_feedback (
    conversation_id bigint not null,
    created_at timestamp(6) with time zone default now() not null,
    updated_at timestamp(6) with time zone default now() not null,
    error_code varchar(40),
    model varchar(50),
