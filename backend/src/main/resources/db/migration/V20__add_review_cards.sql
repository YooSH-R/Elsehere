create table review_cards (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone default now() not null,
    updated_at timestamp(6) with time zone default now() not null,
    user_id bigint not null,
    source_conversation_id bigint not null,
    npc_id bigint not null,
    scene_code varchar(30) not null,
    situation_summary text not null,
    targets jsonb not null,
    practice_count integer default 0 not null,
    last_practiced_at timestamp(6) with time zone,
    used_expressions jsonb not null,
    primary key (id),
    constraint uk_review_cards_user_source unique (user_id, source_conversation_id)
);

create index idx_review_cards_user_id on review_cards (user_id, id desc);
