-- 대화 중 돌발 부탁(S15P31A305-931). 계기 틀·해결처는 규칙(content/npc-favors.json)의 id와 키로만 남기고, 고를 때 정한 보상을 저장한다.
create table npc_favors (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone default now() not null,
    updated_at timestamp(6) with time zone default now() not null,
    user_id bigint not null,
    requester_npc_code varchar(64) not null,
    requester_name varchar(50) not null,
    template_id varchar(64) not null,
    offer_place varchar(64),
    offer_key varchar(32),
    status varchar(10) not null,
    game_day integer not null,
    expires_game_minute bigint,
    ended_game_minute bigint,
    offered_conversation_id bigint not null,
    reward_coins integer not null,
    affinity_delta integer not null,
    primary key (id),
    constraint uk_npc_favors_user_requester_day unique (user_id, requester_npc_code, game_day)
);

create index idx_npc_favors_user_status on npc_favors (user_id, status);
