-- AI 개선(학습·평가)에 쓰는 선택 동의(TRAINING_TEXT·TRAINING_VOICE)와 그 철회 시각,
-- 녹음 음성 활용에 동의한 사용자의 녹음 기록을 추가한다. 기준은 docs/ai-training-data.md를 따른다.
-- 이미 있는 동의 행은 철회하지 않은 상태(withdrawn_at = null)로 둔다.
alter table user_consents drop constraint if exists user_consents_consent_type_check;
alter table user_consents
    add constraint user_consents_consent_type_check
    check ((consent_type in ('TERMS','PRIVACY','AGE14','VOICE','TRAINING_TEXT','TRAINING_VOICE')));
alter table user_consents
    add column withdrawn_at timestamp(6) with time zone;

create table training_recordings (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone default now() not null,
    updated_at timestamp(6) with time zone default now() not null,
    audio_key varchar(100) not null,
    content_type varchar(100) not null,
    conversation_id bigint,
    duration_ms integer,
    purpose varchar(20) not null check ((purpose in ('TURN','TUTORIAL'))),
    recorded_at timestamp(6) with time zone not null,
    request_id uuid not null,
    stt_text text not null,
    user_id bigint not null,
    primary key (id)
);

create index idx_training_recordings_user
    on training_recordings (user_id);
